
# ============================================================
# MNIST 손글씨 숫자 인식 프로그램
# - OpenCV를 이용하여 숫자를 그릴 수 있는 화면 생성
# - 마우스로 작성한 숫자 5개를 이미지로 추출
# - 학습한 딥러닝 모델로 숫자 0~9 인식
#
# 단축키:
# e : 화면 초기화
# s : 작성한 숫자 이미지 확인
# r : 딥러닝 숫자 인식
# q : 프로그램 종료
# ============================================================

import numpy as np
import tensorflow as tf
import cv2 as cv
import matplotlib.pyplot as plt


# ============================================================
# 1. 학습한 딥러닝 모델 불러오기
# ============================================================

# 45~46페이지에서 학습하여 저장한 모델
#
# load_model():
# 저장된 신경망 구조와 가중치를 불러오는 함수
#
# compile=False:
# 예측만 수행하므로 학습용 손실 함수와 옵티마이저를
# 다시 불러오지 않아도 됨

model = tf.keras.models.load_model(
    'dmlp_trained.h5',
    compile=False
)


# ============================================================
# 2. 그림판 초기화 함수
# ============================================================

def reset():
    global img

    # 200x520 크기의 컬러 이미지 생성
    #
    # np.ones():
    # 모든 값이 1인 배열 생성
    #
    # dtype=np.uint8:
    # 0~255 범위의 정수 자료형
    #
    # 255를 곱하면 모든 픽셀이 흰색이 됨

    img = np.ones((200, 520, 3), dtype=np.uint8) * 255

    # 숫자 5개를 작성할 수 있도록 사각형 생성
    #
    # range(5):
    # 0, 1, 2, 3, 4까지 반복
    #
    # cv.rectangle():
    # 이미지에 사각형을 그리는 함수
    #
    # (0, 0, 255):
    # OpenCV는 BGR 순서이므로 빨간색
    #
    # 마지막 인자 1:
    # 사각형 테두리 두께

    for i in range(5):
        cv.rectangle(
            img,
            (i * 100 + 10, 50),
            (i * 100 + 100, 150),
            (0, 0, 255),
            1
        )

    # 사용 가능한 단축키를 화면 상단에 표시
    #
    # cv.putText():
    # 이미지에 문자열을 출력하는 함수
    #
    # FONT_HERSHEY_SIMPLEX:
    # OpenCV에서 제공하는 기본 글꼴

    cv.putText(
        img,
        'e:erase s:show r:recognition q:quit',
        (10, 40),
        cv.FONT_HERSHEY_SIMPLEX,
        0.55,
        (255, 0, 0),
        1
    )


# ============================================================
# 3. 작성한 숫자를 이미지로 추출하는 함수
# ============================================================

def grab_numerals():

    # 숫자 이미지를 저장할 리스트 생성
    numerals = []

    # 총 5개의 숫자를 각각 추출
    for i in range(5):

        # ROI(Region of Interest):
        # 이미지에서 원하는 부분만 잘라내는 영역
        #
        # 각 사각형 안에 작성된 숫자 부분만 추출
        #
        # img[행 시작:행 끝, 열 시작:열 끝]

        roi = img[
            51:149,
            i * 100 + 11:(i + 1) * 100
        ]

        # 컬러 이미지를 흑백 이미지로 변환
        #
        # COLOR_BGR2GRAY:
        # BGR 컬러 이미지를 Grayscale로 변환

        gray = cv.cvtColor(
            roi,
            cv.COLOR_BGR2GRAY
        )

        # 픽셀값 반전
        #
        # 기존 그림판:
        # 흰색 배경(255), 검은색 숫자(0)
        #
        # MNIST 이미지:
        # 검은색 배경(0), 밝은 숫자(255)
        #
        # 255에서 현재 픽셀값을 빼서 반전

        gray = 255 - gray

        # 추출한 숫자 이미지를 28x28로 크기 변경
        #
        # MNIST 모델은 28x28 이미지를 학습했기 때문에
        # 입력 이미지도 동일한 크기로 만들어야 함
        #
        # INTER_CUBIC:
        # 주변 픽셀을 이용한 바이큐빅 보간법

        roi = cv.resize(
            gray,
            (28, 28),
            interpolation=cv.INTER_CUBIC
        )

        # 변환한 숫자 이미지를 리스트에 추가
        numerals.append(roi)

    # 리스트를 NumPy 배열로 변환하여 반환
    #
    # 결과 배열 크기:
    # (5, 28, 28)

    return np.array(numerals)


# ============================================================
# 4. 작성한 숫자 이미지 확인 함수
# ============================================================

def show():

    # 숫자 5개를 추출
    numerals = grab_numerals()

    # Matplotlib 그래프 크기 설정
    plt.figure(figsize=(10, 3))

    for i in range(5):

        # 1행 5열의 그래프 생성
        # i+1번째 위치에 이미지 표시
        plt.subplot(1, 5, i + 1)

        # 숫자를 흑백 이미지로 표시
        #
        # cmap='gray':
        # 흑백 컬러맵 사용
        plt.imshow(
            numerals[i],
            cmap='gray'
        )

        # x축과 y축 눈금 제거
        plt.xticks([])
        plt.yticks([])

    # 숫자 이미지 5개를 화면에 표시
    plt.show()


# ============================================================
# 5. 딥러닝을 이용한 숫자 인식 함수
# ============================================================

def recognition():

    # 화면에 작성된 숫자 5개 추출
    numerals = grab_numerals()

    # 이미지 형태 변환
    #
    # 기존 형태:
    # (5, 28, 28)
    #
    # 변경 형태:
    # (5, 784)
    #
    # 학습 모델의 입력층이 784개이므로
    # 28x28 이미지를 1차원 배열로 변환

    numerals = numerals.reshape(5, 784)

    # 정규화
    #
    # 학습할 때와 동일하게 픽셀값을
    # 0~255에서 0~1 범위로 변환

    numerals = numerals.astype(np.float32) / 255.0

    # 학습한 딥러닝 모델로 숫자 예측
    #
    # predict():
    # 입력 이미지를 모델에 전달하여 결과 계산
    #
    # 결과 형태:
    # (5, 10)
    #
    # 이미지 5개 각각에 대해
    # 숫자 0~9의 예측 확률 10개 반환

    res = model.predict(
        numerals,
        verbose=0
    )

    # 가장 높은 확률을 가진 숫자 선택
    #
    # np.argmax():
    # 배열에서 가장 큰 값의 인덱스를 반환
    #
    # axis=1:
    # 각 행에서 가장 큰 값의 인덱스를 선택
    #
    # 예시:
    # [0.01, 0.02, 0.95, ...]
    # -> 가장 높은 확률의 인덱스 2 반환

    clas = np.argmax(res, axis=1)

    # 인식한 숫자 5개를 화면에 표시
    for i in range(5):

        # 숫자를 작성한 사각형 아래에 예측 결과 출력
        cv.putText(
            img,
            str(clas[i]),
            (i * 100 + 50, 185),
            cv.FONT_HERSHEY_SIMPLEX,
            1,
            (255, 0, 0),
            1
        )

        # 터미널에 숫자와 예측 확률 출력
        #
        # np.max(res[i]):
        # i번째 이미지에서 가장 높은 예측 확률
        #
        # 100을 곱하여 백분율로 변환

        print(
            f"{i + 1}번째 숫자: {clas[i]} "
            f"(확률: {np.max(res[i]) * 100:.2f}%)"
        )


# ============================================================
# 6. 마우스 브러시 설정
# ============================================================

# 브러시 크기(반지름)
BrushSiz = 4

# 브러시 색상
#
# OpenCV는 BGR 색상 체계 사용
# (0, 0, 0) = 검은색

LColor = (0, 0, 0)


# ============================================================
# 7. 마우스로 숫자를 그리는 함수
# ============================================================

def writing(event, x, y, flags, param):

    # event:
    # 마우스 클릭 및 이동 이벤트
    #
    # x, y:
    # 현재 마우스 좌표
    #
    # flags:
    # 마우스 버튼이 눌려 있는지 등의 상태

    # 마우스 왼쪽 버튼을 눌렀을 때
    if event == cv.EVENT_LBUTTONDOWN:

        # 클릭한 위치에 검은색 원 그리기
        #
        # cv.circle():
        # 원을 그리는 함수
        #
        # -1:
        # 원 내부를 색상으로 채우기

        cv.circle(
            img,
            (x, y),
            BrushSiz,
            LColor,
            -1
        )

    # 왼쪽 버튼을 누른 상태에서 마우스를 움직일 때
    elif (
        event == cv.EVENT_MOUSEMOVE
        and flags & cv.EVENT_FLAG_LBUTTON
    ):

        # 마우스가 이동하는 위치마다 원을 그려
        # 손글씨처럼 숫자를 작성할 수 있도록 함
        cv.circle(
            img,
            (x, y),
            BrushSiz,
            LColor,
            -1
        )


# ============================================================
# 8. 프로그램 초기 설정
# ============================================================

# 흰색 그림판과 숫자 작성 영역 생성
reset()

# Writing이라는 이름의 OpenCV 창 생성
cv.namedWindow('Writing')

# Writing 창에서 마우스 이벤트 발생 시
# writing() 함수가 실행되도록 연결
cv.setMouseCallback('Writing', writing)


# ============================================================
# 9. 프로그램 실행 반복문
# ============================================================

# 사용자가 q를 누르기 전까지 계속 실행
while True:

    # 현재 그림판 이미지를 화면에 표시
    cv.imshow('Writing', img)

    # 키보드 입력 확인
    #
    # waitKey(1):
    # 1ms 동안 키보드 입력을 기다림
    #
    # & 0xFF:
    # 입력값의 하위 8비트만 사용

    key = cv.waitKey(1) & 0xFF

    # e 키: 그림판 초기화
    if key == ord('e'):
        reset()

    # s 키: 작성한 숫자 이미지 확인
    elif key == ord('s'):
        show()

    # r 키: 딥러닝 모델로 숫자 인식
    elif key == ord('r'):
        recognition()

    # q 키: 프로그램 종료
    elif key == ord('q'):
        break


# ============================================================
# 10. 프로그램 종료
# ============================================================

# 생성한 모든 OpenCV 창 닫기
cv.destroyAllWindows()
